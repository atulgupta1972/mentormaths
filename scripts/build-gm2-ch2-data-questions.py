# Spread correct_index evenly across A–H (rotate each options list).
def rebalance(rows):
    targets = [3, 6, 1, 4, 7, 2, 5, 0]
    for i, row in enumerate(rows):
        want = targets[i % 8]
        cur = row["correct_index"]
        opts = row["options"]
        ans = opts[cur]
        # rotate left by (cur - want) so ans lands on want
        shift = (cur - want) % 8
        row["options"] = opts[shift:] + opts[:shift]
        row["correct_index"] = want
        assert row["options"][want] == ans
    return rows

EXP = rebalance(EXP)
