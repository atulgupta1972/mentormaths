def q(topic, question, options, correct_index, hint, explanation, difficulty="Medium",
      needs_diagram=False, diagram_file=None, chart=None, table=None, answer_unit=None):
    assert len(options) == 8, question
    assert 0 <= correct_index <= 7, question
    row = {
        "topic": topic,
        "question": question,
        "options": options,
        "correct_index": correct_index,
        "hint": hint,
        "explanation": explanation,
        "difficulty": difficulty,
        "needs_diagram": needs_diagram,
    }
    if answer_unit:
        row["answer_unit"] = answer_unit
    if diagram_file:
        row["diagram_file"] = diagram_file
    if chart:
        row["chart"] = chart
    if table:
        row["table"] = table
    return row


